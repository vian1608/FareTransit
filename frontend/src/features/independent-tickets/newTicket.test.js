/** @jest-environment jsdom */
import React from 'react';
import {createRoot} from 'react-dom/client';
import {act,Simulate} from 'react-dom/test-utils';
import IndependentTicketPage from './IndependentTicketPage';
jest.mock('../../shared/api/api',()=>({__esModule:true,default:{get:jest.fn(),post:jest.fn(),patch:jest.fn()},getApiErrorMessage:()=>''}));
jest.mock('../../shared/components/AirlineLogo',()=>()=>null);
jest.mock('./TicketHistory',()=>({__esModule:true,default:()=>null,TicketActivity:()=>null}));
let host,root;
beforeEach(()=>{global.IS_REACT_ACT_ENVIRONMENT=true;host=document.createElement('div');document.body.appendChild(host);root=createRoot(host);act(()=>root.render(<IndependentTicketPage/>));});
afterEach(()=>{act(()=>root.unmount());host.remove();delete global.IS_REACT_ACT_ENVIRONMENT;});
const button=label=>Array.from(host.querySelectorAll('button')).find(b=>b.textContent.trim()===label);
const click=label=>act(()=>button(label).click());
test('New ticket immediately opens a blank flight manual editor and leaves booking import available',()=>{
 expect(host.querySelector('.it-editor')).toBeNull();
 click('+ New ticket');
 expect(host.querySelector('.it-editor')).not.toBeNull();
 expect(button('Flights').className).toBe('it-primary');
 expect(button('Manual Entry').className).toBe('it-primary');
 expect(button('With Booking ID')).toBeDefined();
 click('With Booking ID');
 expect(button('Fetch booking')).toBeDefined();
 click('+ New ticket');
 expect(host.querySelector('.it-editor')).not.toBeNull();
 expect(button('Manual Entry').className).toBe('it-primary');
 expect(button('Fetch booking')).toBeUndefined();
});
test('New ticket resets unsaved fields and closes GDS import',()=>{
 click('+ New ticket');
 const input=host.querySelector('.it-editor input:not([type=checkbox])');
 expect(input).not.toBeNull();
 act(()=>{input.value='Temporary entry';Simulate.change(input);});
 expect(input.value).toBe('Temporary entry');
 click('GDS Import');
 expect(host.querySelector('.it-modal')).not.toBeNull();
 click('+ New ticket');
 expect(host.querySelector('.it-modal')).toBeNull();
 expect(host.querySelector('.it-editor input:not([type=checkbox])').value).toBe('');
});

const disclosure=label=>Array.from(host.querySelectorAll('.it-disclosure-toggle')).find(b=>b.querySelector('strong')?.textContent===label);
const bodyOf=b=>document.getElementById(b.getAttribute('aria-controls'));
test('compact editor preserves entered flight and seat values across collapse and expansion',()=>{
 click('+ New ticket');
 const seat=disclosure('Assigned seats (optional)');
 expect(seat.getAttribute('aria-expanded')).toBe('false');
 expect(bodyOf(seat).hidden).toBe(true);
 click('+ Outbound segment');
 const segment=disclosure('Outbound · Segment 1');
 expect(segment.getAttribute('aria-expanded')).toBe('true');
 const fields=bodyOf(segment);
 const carrier=Array.from(fields.querySelectorAll('label')).find(l=>l.textContent==='Carrier code').querySelector('input');
 act(()=>{carrier.value='DL';Simulate.change(carrier);});
 const renamed=disclosure('Outbound · Segment 1 · DL');
 act(()=>renamed.click());
 expect(bodyOf(renamed).hidden).toBe(true);
 act(()=>renamed.click());
 expect(carrier.value).toBe('DL');
 const itinerary=disclosure('Flight segments');
 act(()=>itinerary.click());
 expect(bodyOf(itinerary).hidden).toBe(true);
 expect(button('GDS Import')).toBeDefined();
 expect(button('Generate preview')).toBeDefined();
 act(()=>itinerary.click());
 expect(bodyOf(itinerary).contains(carrier)).toBe(true);
 const optional=disclosure('Special notes');
 expect(bodyOf(optional).hidden).toBe(true);
 act(()=>optional.click());
 const notes=bodyOf(optional).querySelector('textarea');
 act(()=>{notes.value='Keep this note';Simulate.change(notes);});
 act(()=>optional.click());
 expect(disclosure('Special notes').textContent).toContain('Keep this note');
 act(()=>optional.click());
 expect(notes.value).toBe('Keep this note');
});
